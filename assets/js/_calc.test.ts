// Run with: node --test assets/js/*.test.ts
import assert from 'node:assert/strict';
import test   from 'node:test';
import { calc } from './_calc.ts';

const ok = (cases: [string, string][]) => () => {
    for (const [src, want] of cases) assert.equal(calc(src), want, src);
};

const ko = (...cases: string[]) => () => {
    for (const src of cases) assert.throws(() => calc(src), Error, src);
};

test('precedence', ok([
    ['1+3*3', '10'], ['(1+3)*3', '12'], ['2*(3+(4-1))', '12'], [' ( 7 ) ', '7'],
    ['1+2<<3', '24'], ['1|2^3&4', '3'], ['6&3|8', '10'], ['1<<2+1', '8'],
    ['10-4-3', '3'], ['2*3%4', '2'], ['-3*-2', '6'], ['~5+1', '-5'],
]));

test('power', ok([
    ['2**3**2', '512'], ['(2**3)**2', '64'], ['-2**2', '-4'], ['(-2)**2', '4'],
    ['2**-1', '0.5'], ['-2**-2', '-0.25'], ['2*3**2', '18'], ['0**0', '1'],
    ['4**0.5', '2.0'],
]));

test('floor division and modulo', ok([
    ['-3%7', '4'], ['3%-7', '-4'], ['-3//7', '-1'], ['7//2', '3'], ['-7//2', '-4'],
    ['7.5//2', '3.0'], ['-1.5%1', '0.5'],
]));

test('truncating modulo', ok([['-3%%7', '-3'], ['3%%-7', '3'], ['7%%3', '1']]));

test('xor', ok([['5^3', '6'], ['2^3', '1'], ['-1^5', '-6']]));

test('big integers', ok([
    ['9**9', '387420489'],
    ['1<<100', '1267650600228229401496703205376'],
    ['2**64-1', '18446744073709551615'],
    ['-1>>100', '-1'], ['5>>1000000', '0'], ['~0', '-1'],
]));

test('literals', ok([
    ['0x123', '291'], ['0XfF', '255'], ['0b101', '5'], ['0o17', '15'], ['0x10+1', '17'],
    ['3.5', '3.5'], ['.5', '0.5'], ['1e3', '1000.0'],
]));

test('float formatting', ok([
    ['7/2', '3.5'], ['8/2', '4.0'], ['1/10', '0.1'], ['0.1+0.2', '0.30000000000000004'],
    ['1/10000', '0.0001'], ['1/100000', '1e-05'], ['10.0**15', '1000000000000000.0'],
    ['10.0**16', '1e+16'], ['1e20', '1e+20'], ['-1/3', '-0.3333333333333333'],
]));

test('division by zero', ko('1/0', '1//0', '1%0', '1%%0', '1.5/0.0', '0**-1'));

test('invalid input', ko(
    '', '1+', '(1', '1)', '1 2', 'a', '2***2', 'x=1', '0b2', '1.5&1', '~1.5', '1<<-1', '1<<0.5',
));

test('too large', ko('9**9**9', '2**5000', '1<<5000', '10.0**400', '(-8)**0.5'));
